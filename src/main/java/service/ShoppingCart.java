// Указываем, что класс находится в пакете service
package service;


// Подключаем класс Food из пакета model - основной тип продукта


import model.Food;


// Класс ShoppingCart — корзина покупок
// Хранит список продуктов и предоставляет методы для расчёта сумм
public class ShoppingCart {


    // Массив для хранения всех товаров в корзине
    private Food[] items;


    // Конструктор: инициализирует корзину переданным массивом продуктов
    // Вызывается при создании объекта корзины
    public ShoppingCart(Food[] items) {
        this.items = items; // Сохраняем переданный массив внутрь объекта
    }


    // 1. Получить общую сумму товаров в корзине без скидки


    // Считает: для каждого товара — amount × price
    public double getTotalPriceWithoutDiscount() {


        // Начальное значение суммы
        double total = 0.0;


        // Проходим по каждому товару в корзине.
        // Переменная item — это один продукт
        for (Food item : items) {


            // Добавляем стоимость: количество × цена за кг
            total += item.getAmount() * item.getPrice();
        }


        // Возвращаем итоговую сумму без скидок
        return total;
    }


    // 2. Получить общую сумму товаров в корзине со скидкой


    // Возвращает общую стоимость товаров со скидками (если они есть)
    // Только товары, реализующие интерфейс Discountable, могут иметь скидку
    public double getTotalPriceWithDiscount() {


        // Общая сумма со скидками
        double total = 0.0;


        // Проходим по каждому продукту в корзине
        for (Food item : items) {


            // Вычисляем полную стоимость позиции без учёта скидки
            double itemPrice = item.getAmount() * item.getPrice();


            // Получаем размер скидки для конкретного товара (в долях единицы)
            // Например, 0.60 означает скидку 60%
            double discountPercent = item.getDiscount();


            // Формула: цена * (1 - доля скидки).
            // Если скидка 60% (0.60), то платим 40% (0.40)
            double finalPrice = itemPrice * (1.0 - discountPercent);


            // Добавляем стоимость обработанной позиции к общей сумме корзины
            total += finalPrice;
        }
        // Возвращается итоговая стоимость
        return total;
    }


    // 3. Получить общую сумму всех вегетарианских продуктов в корзине без скидки.
    public double getTotalVegetarianPriceWithoutDiscount() {


        // Объявляем переменную для хранения общей суммы, начинаем с 0р
        double total = 0.0;


        // Проходим по каждому продукту в корзине
        // item — текущий продукт в корзине
        for (Food item : items) {


            // Проверяем: является ли продукт вегетарианским
            if (item.isVegetarian()) {


                // Если продукт вегетарианский — добавляем его стоимость
                // Считаем: количество (в кг) × цена за кг
                total += item.getAmount() * item.getPrice();
            }
        }
        // Возвращаем сумму вегетарианских продуктов без скидки
        return total;
    }
}
